function [R] = eRotation(JD, Na)
%eRotation Расчет матрицы вращения Земли
%   Расчет матрицы вращения Земли на основе количества Юлианских суток от
%   эпохи J2000 и нутации в прямом восхождении
d = JD;
M = d - 0.5 - floor(d - 0.5);
tau = d/36525;
Sm = 1.7533685592 + 0.0172027918051*d + 6.2831853072*M +...
     6.7707139e-6*tau^2 - 4.50876e-10*tau^3;
St = Sm + Na;

R = [ cos(St) sin(St) 0
     -sin(St) cos(St) 0
     0        0       1];
 
end

